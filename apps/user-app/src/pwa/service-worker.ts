/**
 * The hand-written service worker (ADR 0014): a small, reviewable script that caches only the
 * app shell, content-hashed assets and the offline page. Forum content is never cached because
 * an offline device cannot learn that access was revoked.
 */

export interface ServiceWorkerInput {
  readonly version: string;
  /** Content-hashed assets from the client build, served cache-first. */
  readonly assets: readonly string[];
  /** Generic push titles per locale, keyed by the payload's title key. */
  readonly titles: Readonly<Record<string, Readonly<Record<string, string>>>>;
  /** The locale this registration was created for; changes make the worker bytes differ. */
  readonly locale?: string;
}

const ASSET_PREFIX = "/_astro/";
const OFFLINE_URL = "/offline";
const SHELL_URLS = [OFFLINE_URL, "/theme-css"];

/** JSON is safe inside a classic script here: every value is generated by the server. */
function literal(value: unknown): string {
  return JSON.stringify(value).replaceAll("</", "<\\/");
}

/**
 * The worker's version comes from the registration URL (`/sw.js?v=<build>`), so a deploy
 * registers a different script and the old cache is dropped on activate. A query-less
 * registration still works for tests and manual loading.
 */
export function serviceWorkerSource(input: ServiceWorkerInput): string {
  const shell = [...SHELL_URLS, ...input.assets.filter((url) => url.startsWith(ASSET_PREFIX))];

  return `// Bulletin service worker (ADR 0014). Generated; do not edit in the browser.
"use strict";

const BUILD_VERSION = ${literal(input.version)};
const VERSION = new URL(self.location.href).searchParams.get("v") || BUILD_VERSION;
const CACHE_NAME = "bulletin-shell-" + VERSION;
const LOCALE = new URL(self.location.href).searchParams.get("l") || ${literal(input.locale ?? "en")};
const SHELL = ${literal(shell)};
const TITLES = ${literal(input.titles)};
const ASSET_PREFIX = ${literal(ASSET_PREFIX)};
const SHELL_ASSETS = ["/theme-css"];
const OFFLINE_URL = ${literal(OFFLINE_URL)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      // One missing optional asset must not fail the whole install.
      await Promise.all(
        SHELL.map((url) =>
          cache.add(new Request(url, { cache: "reload" })).catch(() => undefined),
        ),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith("bulletin-shell-") && key !== CACHE_NAME)
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "clear") {
    event.waitUntil(
      caches.keys().then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("bulletin-") && key !== CACHE_NAME)
            .map((key) => caches.delete(key)),
        ),
      ),
    );
  }
});

async function cacheFirst(request) {
  const cached = await caches.match(request);

  if (cached !== undefined) {
    return cached;
  }

  try {
    const response = await fetch(request);

    if (response.ok) {
      const cache = await caches.open(CACHE_NAME);
      await cache.put(request, response.clone());
    }

    return response;
  } catch {
    return new Response("", { status: 504, statusText: "Offline" });
  }
}

async function networkWithOfflineFallback(request) {
  try {
    return await fetch(request);
  } catch {
    const offline = await caches.match(OFFLINE_URL);
    return offline ?? new Response("", { status: 503, statusText: "Offline" });
  }
}



function titleFor(locale, key) {
  const language = typeof locale === "string" ? locale.slice(0, 2).toLowerCase() : "en";
  return (
    TITLES[language]?.[key] ??
    TITLES.en?.[key] ??
    TITLES.en?.["push.title.generic"] ??
    ""
  );
}

function openUrl(notificationId) {
  return "/account/notifications?open=" + encodeURIComponent(notificationId);
}

function loginUrl(returnTo) {
  return "/auth/login?return_to=" + encodeURIComponent(returnTo || "/");
}

function safePath(value) {
  if (typeof value !== "string" || value === "") {
    return "";
  }

  try {
    const url = new URL(value, self.location.origin);
    return url.origin === self.location.origin
      ? url.pathname + url.search + url.hash
      : "";
  } catch {
    return "";
  }
}

async function showPush(event) {
  let payload = null;

  try {
    payload = event.data?.json() ?? null;
  } catch {
    try {
      payload = JSON.parse(event.data?.text() ?? "null");
    } catch {
      payload = null;
    }
  }

  const notificationId = typeof payload?.n === "string" ? payload.n : "";
  const titleKey = typeof payload?.t === "string" ? payload.t : "push.title.generic";

  if (notificationId === "") {
    return;
  }

  let preview = null;
  let loginRequired = false;

  try {
    const response = await fetch(
      "/api/notifications/" + encodeURIComponent(notificationId) + "/preview",
      { credentials: "include", headers: { accept: "application/json" } },
    );

    if (response.ok) {
      preview = await response.json();
    } else if (response.status === 401) {
      loginRequired = true;
    }
  } catch {
    // The generic title is still useful when the device cannot reach the forum.
  }

  const previewTitle = typeof preview?.t === "string" ? preview.t : titleKey;
  const title = titleFor(LOCALE, previewTitle);
  const body = typeof preview?.body === "string" ? preview.body : "";
  const url = safePath(preview?.url) || openUrl(notificationId);

  await self.registration.showNotification(title, {
    body,
    tag: "bulletin-notification-" + notificationId,
    data: { url, notificationId, loginRequired },
    icon: "/pwa/icon-192.png",
    badge: "/pwa/icon-192.png",
  });
}

self.addEventListener("push", (event) => {
  event.waitUntil(showPush(event).catch(() => undefined));
});

async function clickTarget(data) {
  const notificationId =
    typeof data.notificationId === "string" ? data.notificationId : "";

  if (notificationId !== "") {
    try {
      const response = await fetch(
        "/api/notifications/" + encodeURIComponent(notificationId) + "/preview",
        { credentials: "include", headers: { accept: "application/json" } },
      );

      if (response.ok) {
        const preview = await response.json();
        const destination = safePath(preview.url);

        if (destination !== "") {
          return destination;
        }
      }

      if (response.status === 401) {
        return loginUrl(openUrl(notificationId));
      }
    } catch {
      // A network failure falls back to the stored destination or the login page.
    }
  }

  const stored = safePath(data.url);

  return data.loginRequired === true
    ? loginUrl(stored || (notificationId === "" ? "/account/notifications" : openUrl(notificationId)))
    : stored || "/account/notifications";
}

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const data = event.notification.data ?? {};

  event.waitUntil(
    (async () => {
      const target = await clickTarget(data);
      const url = new URL(target, self.location.origin);
      const windows = await self.clients.matchAll({
        type: "window",
        includeUncontrolled: true,
      });

      for (const client of windows) {
        if ("focus" in client) {
          try {
            await client.focus();
          } catch {
            // Notifications opened by a test or a background event may lack user activation.
          }
          if ("navigate" in client) {
            await client.navigate(url.href);
          }
          return;
        }
      }

      await self.clients.openWindow(url.href);
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;

  if (request.method !== "GET") {
    return;
  }

  const url = new URL(request.url);

  if (url.origin !== self.location.origin) {
    return;
  }

  // Content-hashed build assets and the precached theme CSS are cache-first; a new HTML shell
  // names new hashes, and the offline page still needs the active theme's tokens.
  if (url.pathname.startsWith(ASSET_PREFIX) || SHELL_ASSETS.includes(url.pathname)) {
    event.respondWith(cacheFirst(request));
    return;
  }

  // Navigations are always network-only, with the offline shell as the only fallback.
  if (request.mode === "navigate") {
    event.respondWith(networkWithOfflineFallback(request));
  }
  // Everything else (API, overlay, attachments, theme assets) stays network-only.
});
`;
}
